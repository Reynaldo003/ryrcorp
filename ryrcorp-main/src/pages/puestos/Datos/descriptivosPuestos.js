export const obtenerDescriptivo = (nombrePuesto) => {
    if (!nombrePuesto) return DESCRIPTIVO_DEFAULT;
    
    const nombreLimpio = nombrePuesto.trim().toLowerCase();
    
    // Buscar en DESCRIPTIVOS_PUESTOS ignorando mayúsculas/minúsculas
    const keys = Object.keys(DESCRIPTIVOS_PUESTOS);
    const matchedKey = keys.find(key => key.toLowerCase() === nombreLimpio);
    
    if (matchedKey) {
        return DESCRIPTIVOS_PUESTOS[matchedKey];
    }
    
    // Si no hay match exacto, buscar por coincidencia parcial (ej: "Asesor de ventas nuevos" vs "Asesor de Ventas Nuevos")
    const partialMatch = keys.find(key => key.toLowerCase().includes(nombreLimpio) || nombreLimpio.includes(key.toLowerCase()));
    
    if (partialMatch) {
        return DESCRIPTIVOS_PUESTOS[partialMatch];
    }
    
    return DESCRIPTIVO_DEFAULT;
};
